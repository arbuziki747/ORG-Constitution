import streamlit as st

def add_bg_from_css():
    st.markdown(
        """
        <style>
        /* Анимированный градиент для главного фона */
        .stApp {
            background: linear-gradient(-45deg, #e0f7fa, #fce4ec, #e8eaf6, #f1f8e9);
            background-size: 400% 400%;
            animation: gradientBG 15s ease infinite;
        }
        
        @keyframes gradientBG {
            0% { background-position: 0% 50%; }
            50% { background-position: 100% 50%; }
            100% { background-position: 0% 50%; }
        }

        /* Делаем боковую панель (sidebar) слегка прозрачной */
        [data-testid="stSidebar"] {
            background-color: rgba(255, 255, 255, 0.65) !important;
            backdrop-filter: blur(10px); /* Эффект размытия подложки */
        }

        /* Делаем верхний колонтитул прозрачным для красоты */
        header {
            background-color: transparent !important;
        }
        
        /* Слегка выделяем заголовки, чтобы они не терялись на фоне */
        h1, h2, h3 {
            color: #1f2937;
            text-shadow: 1px 1px 2px rgba(255,255,255,0.8);
        }
        </style>
        """,
        unsafe_allow_html=True
    )

def main():
    # Настройка страницы (должна быть первой командой)
    st.set_page_config(page_title="Конституция РФ: Дашборд", page_icon="🇷🇺", layout="wide")
    
    # Применяем наш динамический фон
    add_bg_from_css()
    
    st.sidebar.title("🇷🇺 Навигация")
    page = st.sidebar.radio(
        "Выберите раздел для изучения:",
        (
            "Сущность и юридическая сила",
            "История принятия",
            "Формат внесения поправок",
            "Современные поправки"
        )
    )

    st.title("Конституция Российской Федерации: история и современность")
    st.markdown("---")

    # РАЗДЕЛ 1: Сущность и юридическая сила
    if page == "Сущность и юридическая сила":
        st.header("Что такое Конституция РФ и какова её сила?")
        
        col1, col2 = st.columns(2)
        
        with col1:
            st.info("**Чем является:**\n\nЭто Основной закон государства, особый нормативный правовой акт, имеющий высшую юридическую силу. Она определяет основы конституционного строя, организацию государственной власти и базовые права и свободы человека.")
            
        with col2:
            st.success("**Юридическая сила (Ст. 15):**\n\n1. **Высшая юридическая сила:** Ни один другой закон или указ в стране не может противоречить Конституции.\n2. **Прямое действие:** На нормы Конституции можно ссылаться напрямую в суде.\n3. **Верховенство:** Действует на всей территории Российской Федерации.")
            
        st.write("### Структура документа")
        st.markdown("""
        * **Преамбула** (вводная часть с базовыми ценностями).
        * **Раздел первый** (9 глав, 137 статей — основное тело документа).
        * **Раздел второй** (Заключительные и переходные положения).
        """)

    # РАЗДЕЛ 2: История принятия
    elif page == "История принятия":
        st.header("Как принимали действующую Конституцию?")
        
        st.write("Разработка и принятие проходили на фоне тяжелого политического кризиса 1993 года (противостояние Президента Б.Н. Ельцина и Верховного Совета).")
        
        st.warning("**Дата принятия:** 12 декабря 1993 года.")
        
        st.write("### Формат принятия")
        st.markdown("""
        Конституция была принята **всенародным голосованием (референдумом)**. 
        
        **Условия признания референдума состоявшимся:**
        * В голосовании должно было принять участие более 50% зарегистрированных избирателей (явка составила 54,8%).
        * За проект должно было проголосовать более 50% от числа принявших участие (за проголосовало 58,4%).
        
        Конституция официально вступила в силу в день её опубликования в «Российской газете» — **25 декабря 1993 года**.
        """)

    # РАЗДЕЛ 3: Формат внесения поправок
    elif page == "Формат внесения поправок":
        st.header("В каком формате вносят поправки?")
        st.write("Конституция РФ является «жесткой» — процедура ее изменения значительно сложнее, чем у обычных федеральных законов. Порядок изменения строго зависит от того, в какую главу вносятся правки.")
        
        with st.expander("Изменение Глав 1, 2 и 9 (Основы строя, Права и свободы, Поправки)"):
            st.error("""
            **Эти главы нельзя просто «поправить».**
            Если предложение об изменении поддерживают 3/5 голосов депутатов Госдумы и Совета Федерации, то созывается **Конституционное Собрание**.
            Оно либо подтверждает неизменность Конституции, либо разрабатывает проект **новой** Конституции, который принимается 2/3 голосов Конституционного Собрания или выносится на всенародное голосование.
            """)
            
        with st.expander("Изменение Глав 3–8 (Государственное устройство и органы власти)"):
            st.warning("""
            Поправки принимаются в порядке, предусмотренном для принятия Федерального конституционного закона (ФКЗ):
            1. Одобрение не менее 2/3 голосов депутатов Госдумы.
            2. Одобрение не менее 3/4 голосов сенаторов Совета Федерации.
            3. **Обязательное условие:** одобрение органами законодательной власти не менее чем в **2/3 субъектов РФ**.
            Только после этого Президент подписывает закон о поправке.
            """)
            
        with st.expander("Изменение Статьи 65 (Состав субъектов РФ)"):
            st.info("""
            * При принятии нового субъекта в РФ или образовании нового — принимается Федеральный конституционный закон (ФКЗ).
            * При изменении наименования существующего субъекта — новое название просто включается в статью 65 указом Президента.
            """)

    # РАЗДЕЛ 4: Современные поправки
    elif page == "Современные поправки":
        st.header("Современные поправки (2020 год)")
        st.write("Самое масштабное изменение Конституции с 1993 года произошло летом 2020 года. Поправки затронули главы с 3 по 8.")
        
        st.write("### Ключевые блоки поправок:")
        
        col1, col2 = st.columns(2)
        with col1:
            st.markdown("""
            **1. Социальные гарантии**
            * МРОТ закреплен на уровне не ниже прожиточного минимума.
            * Обязательная ежегодная индексация пенсий и социальных пособий.
            
            **2. Защита суверенитета и территории**
            * Прямой запрет на отчуждение территорий РФ и призывы к этому.
            * Приоритет Конституции РФ над решениями межгосударственных органов.
            """)
            
        with col2:
            st.markdown("""
            **3. Государственное устройство**
            * Закрепление статуса Государственного Совета РФ.
            * Усиление роли Госдумы (утверждение кандидатуры Председателя Правительства и министров).
            * Ограничение для высших должностных лиц (запрет на иностранное гражданство).
            
            **4. Традиционные ценности**
            * Защита исторической правды и памяти защитников Отечества.
            * Защита института брака как союза мужчины и женщины.
            """)
            
        st.markdown("---")
        st.write("💡 *Процедура 2020 года была уникальной: помимо стандартного одобрения парламентами субъектов, поправки были вынесены на Общероссийское голосование (1 июля 2020 года).*")

if __name__ == "__main__":
    main()